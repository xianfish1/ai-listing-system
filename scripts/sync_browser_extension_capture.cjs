'use strict';

const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');
const CORE_PATH = path.join(ROOT, 'scripts/mabang_page_import_capture.js');
const OUTPUT_PATH = path.join(ROOT, 'browser_extension/page_capture.js');

function buildPageCapture() {
  const core = fs.readFileSync(CORE_PATH, 'utf8').trim();
  return `// Generated by scripts/sync_browser_extension_capture.cjs. Do not edit by hand.\n` +
`// Runs in the Mabang page MAIN world so Vue state is visible.\n\n` +
`(() => {\n` +
`  const captureFn = ${core};\n\n` +
`  const clean = (value) => String(value ?? '').replace(/\\s+/g, ' ').trim();\n` +
`  const sleep = (milliseconds) => new Promise((resolve) => setTimeout(resolve, milliseconds));\n` +
`  const isVisible = (node) => {\n` +
`    if (!node || !node.isConnected) return false;\n` +
`    const style = getComputedStyle(node);\n` +
`    const rect = node.getBoundingClientRect();\n` +
`    return style.display !== 'none' && style.visibility !== 'hidden' && style.opacity !== '0' && rect.width > 0 && rect.height > 0;\n` +
`  };\n` +
`  const waitUntil = async (predicate, timeout = 6000) => {\n` +
`    const startedAt = Date.now();\n` +
`    while (Date.now() - startedAt < timeout) {\n` +
`      const value = predicate();\n` +
`      if (value) return value;\n` +
`      await sleep(100);\n` +
`    }\n` +
`    return null;\n` +
`  };\n` +
`  const clickForText = (scope, text) => [...scope.querySelectorAll('button,[role="button"],a,label,.el-button,.el-link,.el-radio,span')]\n` +
`    .filter(isVisible).find((node) => clean(node.textContent) === text || clean(node.textContent).startsWith(text));\n` +
`  const promotionDialog = () => [...document.querySelectorAll('.el-dialog,.el-dialog__wrapper,[role="dialog"]')]\n` +
`    .filter(isVisible).find((node) => clean(node.textContent).includes('选择折扣活动'));\n\n` +
`  async function prepareCNSCImportState() {\n` +
`    const currentUrl = new URL(location.href);\n` +
`    let hashParams = new URL(location.origin).searchParams;\n` +
`    try { hashParams = new URL(String(location.hash || '').replace(/^#/, ''), location.origin).searchParams; } catch {}\n` +
`    if (currentUrl.searchParams.get('global') !== '4' && hashParams.get('global') !== '4') return;\n` +
`    const state = { target_site_stores_loaded: false, target_site_stores: [] };\n` +
`    const picker = document.querySelector('#shops-wap');\n` +
`    const pickerTrigger = picker?.querySelector('.shop-box');\n` +
`    let pickerOpened = false;\n` +
`    if (pickerTrigger && !picker?.querySelector('.feat-content')) {\n` +
`      pickerTrigger.click();\n` +
`      pickerOpened = true;\n` +
`      await waitUntil(() => picker?.querySelector('.feat-content'));\n` +
`    }\n` +
`    const aliases = { '台湾': 'TW', '菲律宾': 'PH', '新加坡': 'SG', '泰国': 'TH', '马来西亚': 'MY', '墨西哥': 'MX', '越南': 'VN', '巴西': 'BR', SIP: 'SIP' };\n` +
`    const requiredManualSites = ['TW', 'PH', 'SG', 'TH', 'MY', 'MX', 'VN', 'BR'];\n` +
`    const makeTargetStore = (siteCode, shop) => {\n` +
`      const storeId = clean(shop?.id || shop?.shopId || shop?.store_id || shop?.storeId);\n` +
`      const storeName = clean(shop?.name || shop?.store_name || shop?.storeName);\n` +
`      if (!storeId && !storeName) return null;\n` +
`      return { site_code: siteCode, store_id: storeId, store_name: storeName, discount_catalog_loaded: false, discount_catalog: [] };\n` +
`    };\n` +
`    const shopVm = picker?.__vue__ || picker?.__vueParentComponent?.proxy;\n` +
`    const vueSiteGroups = Array.isArray(shopVm?.shops) ? shopVm.shops : [];\n` +
`    if (vueSiteGroups.length) {\n` +
`      for (const siteGroup of vueSiteGroups) {\n` +
`        const siteCode = clean(siteGroup?.site).toUpperCase();\n` +
`        if (!requiredManualSites.includes(siteCode)) continue;\n` +
`        const selected = (Array.isArray(siteGroup?.shops) ? siteGroup.shops : []).filter((shop) => shop?.isChecked === true);\n` +
`        if (selected.length !== 1) continue;\n` +
`        const target = makeTargetStore(siteCode, selected[0]);\n` +
`        if (target) state.target_site_stores.push(target);\n` +
`      }\n` +
`    } else {\n` +
`      const siteGroups = [...(picker?.querySelectorAll('.site') || [])];\n` +
`      for (const siteGroup of siteGroups) {\n` +
`        const titleText = clean(siteGroup.querySelector('.title-wap-checkbox')?.textContent || siteGroup.textContent);\n` +
`        const rawCode = clean(siteGroup.dataset.siteCode || '').toUpperCase();\n` +
`        const siteCode = /^(TW|PH|SG|TH|MY|MX|VN|BR|SIP)$/.test(rawCode) ? rawCode : Object.entries(aliases).find(([name]) => titleText.includes(name))?.[1] || '';\n` +
`        if (!requiredManualSites.includes(siteCode)) continue;\n` +
`        const selected = [...siteGroup.querySelectorAll('.shops-checkbox')].filter((label) => label.querySelector('input[type="checkbox"]')?.checked);\n` +
`        if (selected.length !== 1) continue;\n` +
`        const label = selected[0];\n` +
`        const input = label.querySelector('input[type="checkbox"]');\n` +
`        const target = makeTargetStore(siteCode, { id: label.dataset.storeId || label.dataset.shopId || input?.dataset.storeId || input?.dataset.shopId || input?.value, name: label.dataset.storeName || label.dataset.shopName || label.textContent });\n` +
`        if (target) state.target_site_stores.push(target);\n` +
`      }\n` +
`    }\n` +
`    const targetCodes = state.target_site_stores.map((item) => item.site_code);\n` +
`    state.target_site_stores_loaded = Boolean(picker && requiredManualSites.every((code) => targetCodes.filter((value) => value === code).length === 1) && new Set(targetCodes).size === requiredManualSites.length);\n` +
`    if (pickerOpened) {\n` +
`      const cancel = clickForText(picker, '取消');\n` +
`      if (cancel) cancel.click();\n` +
`      else state.target_site_stores_loaded = false;\n` +
`    }\n` +
`    const visibleHeaders = [...document.querySelectorAll('.vxe-header--column')].filter(isVisible);\n` +
`    const siteHeaderCodes = visibleHeaders.map((node) => { const text = clean(node.textContent).toUpperCase(); return /^(TW|PH|SG|TH|MY|MX|VN|BR)$/.test(text) ? text : ''; });\n` +
`    const activityHeaders = visibleHeaders.map((node, index) => ({ node, index, text: clean(node.textContent) })).filter((entry) => entry.text.includes('折扣活动'));\n` +
`    const findSiteForActivityHeader = (entry) => {\n` +
`      for (let i = entry.index; i >= 0; i -= 1) { if (siteHeaderCodes[i]) return siteHeaderCodes[i]; }\n` +
`      for (let node = entry.node.parentElement; node; node = node.parentElement) {\n` +
`        const code = clean(node?.dataset?.siteCode || '').toUpperCase();\n` +
`        if (/^(TW|PH|SG|TH|MY|MX|VN|BR)$/.test(code)) return code;\n` +
`      }\n` +
`      return '';\n` +
`    };\n` +
`    const findTriggerIn = (header) => header.querySelector('.change-discount') || [...header.querySelectorAll('button,[role="button"],.el-button,.el-link,a,span')].find((node) => isVisible(node) && (clean(node.textContent) === '选择活动' || clean(node.textContent).includes('选择折扣')));\n` +
`    for (const entry of activityHeaders) {\n` +
`      const siteCode = findSiteForActivityHeader(entry);\n` +
`      const store = siteCode ? state.target_site_stores.find((item) => item.site_code === siteCode) : null;\n` +
`      if (store) {\n` +
`        const headerText = clean(entry.node.textContent).replace(/^折扣活动[\\s·:：]*/, '');\n` +
`        const percentMatch = headerText.match(/(\\d+(?:\\.\\d+)?)\\s*%/);\n` +
`        if (percentMatch) store.discount_percent = Number(percentMatch[1]);\n` +
`        const stripped = headerText.replace(/(\\d+(?:\\.\\d+)?)\\s*%(?:OFF)?/i, '').replace(/选择活动|批量修改|活动待配置/g, '').trim();\n` +
`        if (stripped) { store.discount_name = stripped; store.discount_label = stripped; }\n` +
`      }\n` +
`      const trigger = store ? findTriggerIn(entry.node) : null;\n` +
`      if (!store || !trigger) continue;\n` +
`      let dialog = null;\n` +
`      try {\n` +
`        trigger.click();\n` +
`        dialog = await waitUntil(promotionDialog);\n` +
`        if (!dialog) continue;\n` +
`        await waitUntil(() => ![...dialog.querySelectorAll('.el-loading-mask')].some(isVisible));\n` +
`        const containers = [];\n` +
`        for (let vm = dialog.__vue__ || dialog.__vueParentComponent?.proxy, depth = 0; vm && depth < 8; vm = vm.$parent, depth += 1) containers.push(vm, vm.$data);\n` +
`        const rawOptions = containers.flatMap((item) => ['tableData', 'activityList', 'promotionList', 'discountList'].flatMap((key) => Array.isArray(item?.[key]) ? item[key] : []));\n` +
`        const seen = new Set();\n` +
`        store.discount_catalog = rawOptions.map((item) => {\n` +
`          const id = clean(item.discount_id || item.discountId || item.activity_id || item.activityId || item.id);\n` +
`          return { mabang_discount_id: id, name: clean(item.discount_name || item.discountName || item.activity_name || item.name), discount_percent: Number(clean(item.discount_percent || item.discountPercent || item.discount_rate || item.discountRate).replace('%', '')) || '', selected: item.selected === true || item.checked === true };\n` +
`        }).filter((item) => item.mabang_discount_id && item.name && !seen.has(item.mabang_discount_id) && seen.add(item.mabang_discount_id));\n` +
`        let selected = store.discount_catalog.filter((item) => item.selected);\n` +
`        if (selected.length !== 1) {\n` +
`          const headerText = clean(entry.node.textContent);\n` +
`          selected = store.discount_catalog.filter((item) => headerText.includes(item.name));\n` +
`        }\n` +
`        store.discount_catalog_loaded = store.discount_catalog.length > 0 && selected.length === 1;\n` +
`        if (store.discount_catalog_loaded) {\n` +
`          store.mabang_discount_id = selected[0].mabang_discount_id;\n` +
`          store.discount_name = selected[0].name;\n` +
`          store.discount_label = selected[0].name;\n` +
`          store.discount_percent = selected[0].discount_percent;\n` +
`        }\n` +
`      } finally {\n` +
`        if (dialog) {\n` +
`          const close = dialog.querySelector('.el-dialog__headerbtn,[aria-label="Close"],[aria-label="关闭"]') || clickForText(dialog, '取消') || clickForText(dialog, '关闭');\n` +
`          if (close) close.click();\n` +
`          await waitUntil(() => !promotionDialog());\n` +
`        }\n` +
`      }\n` +
`    }\n` +
`    window.__AI_LISTING_CNSC_IMPORT_STATE__ = state;\n` +
`  }\n\n` +
`  const handleRequest = async (event) => {\n` +
`    if (event.source !== window) return;\n` +
`    const msg = event.data;\n` +
`    if (!msg || msg.type !== '__AI_LISTING_CAPTURE_REQUEST__') return;\n` +
`    try {\n` +
`      await prepareCNSCImportState();\n` +
`      const capture = captureFn(msg.plan || {});\n` +
`      window.postMessage({ type: '__AI_LISTING_CAPTURE_RESULT__', requestId: msg.requestId, ok: true, capture }, '*');\n` +
`    } catch (error) {\n` +
`      window.postMessage({ type: '__AI_LISTING_CAPTURE_RESULT__', requestId: msg.requestId, ok: false, error: String(error?.message || error) }, '*');\n` +
`    }\n` +
`  };\n` +
`  window.addEventListener('message', handleRequest);\n` +
`  window.postMessage({ type: '__AI_LISTING_CAPTURE_READY__' }, '*');\n` +
`})();\n`;
}

if (require.main === module) fs.writeFileSync(OUTPUT_PATH, buildPageCapture(), 'utf8');

module.exports = { buildPageCapture };
